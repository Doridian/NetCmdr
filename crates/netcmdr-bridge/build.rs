//! Bakes the web client into the bridge.
//!
//! The bridge is a single binary: it serves the browser client from its own
//! `.text`, not from a directory it was pointed at. This script is where that
//! happens — it reads the client `tools/build-web.sh` produced and writes a
//! table of it into `OUT_DIR` for `src/assets.rs` to `include!`.
//!
//! Everything is stored **brotli-compressed**, at the maximum quality, for two
//! reasons. It is a third of the size in the executable, and it is the form
//! most browsers will be served, so the expensive compression happens once here
//! rather than on every start of the service. The plain and gzip copies are
//! made from these bytes when the bridge starts, which is under half a second
//! for a client this size where the brotli is closer to half a minute.
//!
//! A file brotli does not shrink — a PNG, say — is stored as it is instead, so
//! that nothing is larger in the binary than it was on disk.
//!
//! # Where the client comes from
//!
//! `crates/netcmdr-web/dist`, or `$NETCMDR_WEB_DIST` if that is set. A missing or
//! empty directory is a warning rather than an error: the bridge still builds
//! and still relays the protocol, it just has no client to hand out. That keeps
//! `cargo build --workspace` working for someone who has no wasm toolchain
//! installed, which is most people touching the native crates.

use std::io::Write;
use std::path::{Path, PathBuf};

/// Brotli's maximum quality, and the largest window the format defines without
/// the negotiated extension not every browser has.
const BROTLI_QUALITY: u32 = 11;
const BROTLI_WINDOW: u32 = 22;

/// How deep to walk. A symlinked directory can point at its own parent, and
/// this is cheaper than remembering every inode visited.
const MAX_DEPTH: usize = 16;

/// Refuse to embed a file larger than this. The client's module is about four
/// megabytes; the ceiling is here so that something unrelated dropped into the
/// directory cannot quietly produce a gigabyte-long executable.
const MAX_SIZE: u64 = 128 * 1024 * 1024;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=NETCMDR_WEB_DIST");

    let dist = dist_dir();
    // Named even when it does not exist: cargo then reruns this script once the
    // directory appears, so a `build-web.sh` after a `cargo build` is picked up
    // by the next one rather than needing a `cargo clean`.
    println!("cargo:rerun-if-changed={}", dist.display());

    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let staging = out.join("assets");
    // The table is regenerated whole, so anything left from a previous dist —
    // a file since renamed or deleted — must not survive into this one.
    std::fs::remove_dir_all(&staging).ok();

    let mut files = Vec::new();
    collect(&dist, &dist, 0, &mut files);
    // Sorted so that the generated file is identical between builds of an
    // identical directory, whatever order the filesystem listed it in.
    files.sort();

    if files.is_empty() {
        println!(
            "cargo:warning=no web client in {}: this netcmdr-bridge will serve the \
             protocol routes only. Build it with tools/build-web.sh and build \
             the bridge again.",
            dist.display()
        );
    }

    let mut table = String::from(
        "// Generated by build.rs. The web client, as it sits in the binary.\n\
         pub(crate) static EMBEDDED: &[Embedded] = &[\n",
    );
    for relative in &files {
        table.push_str(&embed(&dist, relative, &staging));
    }
    table.push_str("];\n");

    std::fs::write(out.join("embedded.rs"), table).expect("writing the asset table");
}

/// Where the built client is.
fn dist_dir() -> PathBuf {
    if let Some(dir) = std::env::var_os("NETCMDR_WEB_DIST") {
        return PathBuf::from(dir);
    }
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    manifest.join("../netcmdr-web/dist")
}

/// Compress one file into `staging` and return its row of the table.
fn embed(dist: &Path, relative: &str, staging: &Path) -> String {
    let source = dist.join(relative);
    println!("cargo:rerun-if-changed={}", source.display());

    let plain =
        std::fs::read(&source).unwrap_or_else(|e| panic!("reading {}: {e}", source.display()));
    let plain_len = plain.len();
    let packed = brotli(&plain);

    // Brotli makes an already-compressed file slightly bigger. Storing the
    // original in that case keeps the binary as small as it can be, and the
    // bridge then simply has no brotli copy of that file to offer.
    let compressed = packed.len() < plain_len;
    // The two forms are staged in separate trees rather than told apart by a
    // `.br` on the end: a client that happened to ship both `x` and `x.br`
    // would otherwise have one silently overwrite the other here.
    let (body, tree) = if compressed {
        (packed, "brotli")
    } else {
        (plain, "stored")
    };

    let target = staging.join(tree).join(relative);
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent)
            .unwrap_or_else(|e| panic!("creating {}: {e}", parent.display()));
    }
    std::fs::write(&target, &body).unwrap_or_else(|e| panic!("writing {}: {e}", target.display()));

    format!(
        "    Embedded {{\n        \
             path: {path:?},\n        \
             plain_len: {plain_len},\n        \
             brotli: {compressed},\n        \
             body: include_bytes!({target:?}),\n    \
         }},\n",
        path = relative,
        target = target,
    )
}

/// Every file under `dist`, depth-first, as paths relative to it.
fn collect(dist: &Path, dir: &Path, depth: usize, out: &mut Vec<String>) {
    if depth > MAX_DEPTH {
        println!("cargo:warning=not descending past {}", dir.display());
        return;
    }
    let Ok(entries) = std::fs::read_dir(dir) else {
        return; // no client built; main() warns about the empty result
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        // `file_type` does not follow symlinks and `metadata` does, so a link
        // to a file is embedded and a link to a directory is not descended.
        if kind.is_dir() {
            collect(dist, &path, depth + 1, out);
            continue;
        }
        let Ok(meta) = std::fs::metadata(&path) else {
            continue;
        };
        if !meta.is_file() {
            continue;
        }
        if meta.len() > MAX_SIZE {
            println!(
                "cargo:warning={} is {} MiB; not embedding it",
                path.display(),
                meta.len() / (1024 * 1024)
            );
            continue;
        }
        let Ok(relative) = path.strip_prefix(dist) else {
            continue;
        };
        match url_key(relative) {
            Some(key) => out.push(key),
            // No URL can ask for a name that is not UTF-8, so embedding it
            // would only make the binary bigger.
            None => println!(
                "cargo:warning={} is not valid UTF-8; not embedding it",
                path.display()
            ),
        }
    }
}

/// A path under the client's root, keyed the way a URL spells it.
///
/// Joined with `/` whatever this host's separator is, and built component by
/// component rather than by replacing separators, because a backslash is a
/// legal character in a filename on the systems where it is not one.
fn url_key(relative: &Path) -> Option<String> {
    let mut key = String::new();
    for component in relative.components() {
        let part = component.as_os_str().to_str()?;
        if !key.is_empty() {
            key.push('/');
        }
        key.push_str(part);
    }
    Some(key)
}

fn brotli(plain: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    let mut encoder = brotli::CompressorWriter::new(
        &mut out,
        // Buffer size; the input is already in memory, so this only sets how
        // often the encoder is handed more of it.
        64 * 1024,
        BROTLI_QUALITY,
        BROTLI_WINDOW,
    );
    encoder.write_all(plain).expect("brotli writes to a Vec");
    drop(encoder);
    out
}
